#!/usr/bin/env node
'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT_FILES = new Set(['Dockerfile', '.dockerignore', 'Cargo.toml', 'Cargo.lock']);
const EXCLUDED_SOURCE = /(?:^|\/)(?:bin\/paykit-(?:backup|receipt)-fixture\.rs|[^/]+_tests\.rs)$/;
const GENERATED_DIR = path.join('build-resources', 'paykit-service');

const posix = value => value.split(path.sep).join('/');
const sha256 = value => crypto.createHash('sha256').update(value).digest('hex');
const canonicalRecords = files =>
  files
    .slice()
    .sort((a, b) => a.path.localeCompare(b.path))
    .map(file => `${file.path}\0${file.size}\0${file.sha256}\n`)
    .join('');

function walk(directory, prefix = '', ignoredRootDirectories = new Set()) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const relative = posix(path.join(prefix, entry.name));
    const absolute = path.join(directory, entry.name);
    if (!prefix && entry.isDirectory() && ignoredRootDirectories.has(entry.name)) return [];
    if (entry.isSymbolicLink()) throw new Error(`Symlinks are not allowed: ${relative}`);
    if (entry.isDirectory()) return walk(absolute, relative, ignoredRootDirectories);
    if (!entry.isFile()) throw new Error(`Only regular files are allowed: ${relative}`);
    return [relative];
  });
}

function allowedFiles(sourceDirectory) {
  const entries = walk(sourceDirectory, '', new Set(['.git', 'target']));
  const unexpected = entries.filter(
    item =>
      !ROOT_FILES.has(item) &&
      !item.startsWith('src/') &&
      !item.startsWith('tests/'),
  );
  if (unexpected.length) throw new Error(`Unexpected Paykit inputs: ${unexpected.join(', ')}`);
  for (const required of ROOT_FILES) {
    if (!entries.includes(required)) throw new Error(`Missing required Paykit input: ${required}`);
  }
  const files = entries.filter(
    item => ROOT_FILES.has(item) || (item.startsWith('src/') && !EXCLUDED_SOURCE.test(item)),
  );
  if (!files.includes('src/main.rs')) throw new Error('Missing required Paykit input: src/main.rs');
  return files.sort();
}

function createManifest(sourceDirectory, appVersion) {
  const files = allowedFiles(sourceDirectory).map(relative => {
    const body = fs.readFileSync(path.join(sourceDirectory, relative));
    return { path: relative, size: body.length, sha256: sha256(body) };
  });
  const contextDigest = sha256(canonicalRecords(files));
  return {
    schemaVersion: 1,
    appVersion,
    imageTag: `polar-paykit/service:${appVersion}-${contextDigest.slice(0, 16)}`,
    contextDigest,
    supportedArchitectures: ['amd64', 'arm64'],
    files,
  };
}

function copyContext(sourceDirectory, destinationDirectory, manifest) {
  fs.rmSync(destinationDirectory, { recursive: true, force: true });
  fs.mkdirSync(destinationDirectory, { recursive: true });
  for (const file of manifest.files) {
    if (!fs.lstatSync(path.join(sourceDirectory, file.path)).isFile())
      throw new Error(`Only regular files are allowed: ${file.path}`);
    const destination = path.join(destinationDirectory, file.path);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(path.join(sourceDirectory, file.path), destination, fs.constants.COPYFILE_EXCL);
  }
  fs.writeFileSync(
    path.join(destinationDirectory, 'service-image.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );
}

function verifyContext(directory, manifest) {
  const actual = walk(directory).filter(file => file !== 'service-image.json').sort();
  const expected = manifest.files.map(file => file.path).sort();
  if (JSON.stringify(actual) !== JSON.stringify(expected)) throw new Error('Context file set differs from manifest');
  const checked = actual.map(relative => {
    const body = fs.readFileSync(path.join(directory, relative));
    const record = manifest.files.find(file => file.path === relative);
    if (!record || record.size !== body.length || record.sha256 !== sha256(body)) {
      throw new Error(`Context integrity check failed: ${relative}`);
    }
    return record;
  });
  if (sha256(canonicalRecords(checked)) !== manifest.contextDigest) throw new Error('Context digest mismatch');
}

function run(repositoryRoot = path.resolve(__dirname, '..')) {
  const packageJson = JSON.parse(fs.readFileSync(path.join(repositoryRoot, 'package.json'), 'utf8'));
  const source = path.join(repositoryRoot, 'paykit');
  const destination = path.join(repositoryRoot, GENERATED_DIR);
  const manifest = createManifest(source, packageJson.version);
  copyContext(source, destination, manifest);
  verifyContext(destination, manifest);
  const manifestText = fs.readFileSync(path.join(destination, 'service-image.json'));
  const generated = `// Generated by scripts/package-paykit-context.js; do not edit.\n` +
    `export const PAYKIT_IMAGE_MANIFEST_SHA256 =\n  '${sha256(manifestText)}';\n` +
    `export const PAYKIT_IMAGE_CONTEXT_SHA256 =\n  '${manifest.contextDigest}';\n` +
    `export const PAYKIT_IMAGE_TAG = '${manifest.imageTag}';\n`;
  fs.writeFileSync(path.join(repositoryRoot, 'src', 'shared', 'paykitImageMetadata.ts'), generated);
  return manifest;
}

if (require.main === module) {
  const manifest = run();
  process.stdout.write(`Prepared Paykit service context ${manifest.contextDigest.slice(0, 16)}\n`);
}

module.exports = { allowedFiles, canonicalRecords, createManifest, copyContext, run, sha256, verifyContext };
